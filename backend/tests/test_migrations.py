from pathlib import Path

from alembic import command
from alembic.config import Config
from sqlalchemy import inspect

from app.config import BACKEND_DIR
from app.database import create_db_engine

APP_TABLES = {"departments", "teachers", "students"}


def make_alembic_config(database_url: str) -> Config:
    config = Config(str(BACKEND_DIR / "alembic.ini"))
    config.set_main_option("sqlalchemy.url", database_url)
    return config


def table_names(database_url: str) -> set[str]:
    engine = create_db_engine(database_url)
    try:
        return set(inspect(engine).get_table_names())
    finally:
        engine.dispose()


def test_upgrade_and_downgrade_run_on_fresh_sqlite(tmp_path: Path) -> None:
    database_url = f"sqlite:///{tmp_path / 'migrations.db'}"
    config = make_alembic_config(database_url)

    command.upgrade(config, "head")
    assert table_names(database_url) == APP_TABLES | {"alembic_version"}

    command.downgrade(config, "base")
    assert table_names(database_url) == {"alembic_version"}

    command.upgrade(config, "head")
    assert table_names(database_url) == APP_TABLES | {"alembic_version"}


def test_models_and_migrations_are_in_sync(tmp_path: Path) -> None:
    """Fails if a model changed without a matching migration (`alembic check`)."""
    config = make_alembic_config(f"sqlite:///{tmp_path / 'check.db'}")
    command.upgrade(config, "head")

    command.check(config)  # raises AutogenerateDiffsDetected on any difference
